CREATE TABLE IF NOT EXISTS oms_order_shipment_outbound (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 company_code VARCHAR(50) COLLATE utf8mb4_bin NOT NULL,
 shipment_id BIGINT NOT NULL,
 shipment_sn VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 request_id VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 source_mode VARCHAR(12) NOT NULL,
 remote_event_id BIGINT NULL,
 message_id VARCHAR(128) NOT NULL DEFAULT '',
 final_confirmation TINYINT NOT NULL DEFAULT 0,
 outbound_time DATETIME NULL,
 quantity BIGINT NOT NULL,
 payload_json MEDIUMTEXT NOT NULL,
 payload_hash VARCHAR(64) NOT NULL,
 state VARCHAR(24) NOT NULL DEFAULT 'PENDING',
 attempts INT NOT NULL DEFAULT 0,
 last_error VARCHAR(1000) NOT NULL DEFAULT '',
 created_by VARCHAR(100) NOT NULL,
 next_attempt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 completed_at DATETIME NULL,
 UNIQUE KEY outbound_request(company_code,request_id),
 UNIQUE KEY warehouse_event(company_code,remote_event_id),
 KEY shipment_records(company_code,shipment_id,id),
 KEY receipt_due(state,next_attempt)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS oms_order_shipment_package (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 company_code VARCHAR(50) COLLATE utf8mb4_bin NOT NULL,
 shipment_id BIGINT NOT NULL,
 outbound_id BIGINT NULL,
 package_code VARCHAR(100) COLLATE utf8mb4_bin NOT NULL,
 carrier_code VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 carrier_name VARCHAR(100) NOT NULL,
 warehouse_carrier_code VARCHAR(64) NOT NULL DEFAULT '',
 express_code VARCHAR(100) COLLATE utf8mb4_bin NOT NULL,
 source_mode VARCHAR(12) NOT NULL,
 payload_hash VARCHAR(64) NOT NULL,
 request_id VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 quantity BIGINT NOT NULL,
 outbound_time DATETIME NULL,
 created_by VARCHAR(100) NOT NULL,
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY package_code(company_code,shipment_id,package_code),
 UNIQUE KEY package_waybill(company_code,carrier_code,express_code),
 UNIQUE KEY package_request(company_code,request_id),
 KEY shipment_packages(company_code,shipment_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS oms_order_shipment_package_line (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 company_code VARCHAR(50) COLLATE utf8mb4_bin NOT NULL,
 package_id BIGINT NOT NULL,
 shipment_line_id BIGINT NOT NULL,
 sku_sn VARCHAR(128) COLLATE utf8mb4_bin NOT NULL,
 platform_oid VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 quantity BIGINT NOT NULL,
 UNIQUE KEY package_line(company_code,package_id,shipment_line_id),
 KEY shipment_line_packages(company_code,shipment_line_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
