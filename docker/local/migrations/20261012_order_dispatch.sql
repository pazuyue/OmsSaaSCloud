CREATE TABLE IF NOT EXISTS oms_order_shipment_dispatch (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 company_code VARCHAR(50) COLLATE utf8mb4_bin NOT NULL,
 shipment_id BIGINT NOT NULL,
 shipment_sn VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 payload_json MEDIUMTEXT NOT NULL,
 payload_hash VARCHAR(64) NOT NULL,
 state VARCHAR(24) NOT NULL DEFAULT 'PENDING',
 remote_task_id BIGINT NULL,
 external_order VARCHAR(100) NOT NULL DEFAULT '',
 warehouse_status VARCHAR(40) NOT NULL DEFAULT '',
 last_error VARCHAR(1000) NOT NULL DEFAULT '',
 query_message VARCHAR(1000) NOT NULL DEFAULT '',
 last_query_at DATETIME NULL,
 attempts INT NOT NULL DEFAULT 0,
 lease_token VARCHAR(64) NULL,
 lease_until DATETIME NULL,
 next_attempt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 created_by VARCHAR(100) NOT NULL,
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY shipment_dispatch(company_code,shipment_id),
 UNIQUE KEY shipment_dispatch_sn(company_code,shipment_sn),
 KEY dispatch_due(company_code,state,next_attempt)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='发货单下发意图及固定快照，不更新库存或实际出库数量';
