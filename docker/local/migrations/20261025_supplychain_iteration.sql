-- 采购收货差异事实与处理结果；不作为实收或库存记账凭据。
CREATE TABLE IF NOT EXISTS purchase_receipt_difference (
 id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '收货差异记录ID',
 company_code VARCHAR(64) NOT NULL COMMENT '所属公司，所有查询和操作必须隔离',
 task_id BIGINT NOT NULL COMMENT '原真实采购入库任务ID',
 ticket_id BIGINT NOT NULL COMMENT '原采购入库执行单ID',
 ticket_sn VARCHAR(100) NOT NULL COMMENT '原实际采购入库单号',
 message_id VARCHAR(128) NOT NULL COMMENT '原仓库回传消息ID',
 receipt_hash CHAR(64) NOT NULL COMMENT '原回传内容摘要，同一回传同类差异只记录一次',
 difference_kind VARCHAR(24) NOT NULL COMMENT 'SHORT最终短收、QUALITY次品、OVER超收、WRONG_SKU错货、LATE迟到额度冲突',
 expected_quantity BIGINT NOT NULL COMMENT '原本批安排数量快照',
 reported_quantity BIGINT NOT NULL COMMENT '本次原回传数量，不代表已确认实收',
 difference_quantity BIGINT NOT NULL COMMENT '短收或次品等本次差异数量快照',
 receipt_json JSON NOT NULL COMMENT '已验签并绑定仓库与货主的原回传，保留实际SKU批次与正次品',
 source_log_id BIGINT NOT NULL DEFAULT 0 COMMENT '原仓库交互日志ID，报文查看沿用独立权限',
 state VARCHAR(24) NOT NULL DEFAULT 'OPEN' COMMENT 'OPEN待处理、WAITING等仓库更正、RESOLVED已处理、REJECTED拒收、CORRECTED后续更正已接收',
 decision VARCHAR(24) NOT NULL DEFAULT '' COMMENT 'REARRANGE补建到货、KEEP_BAD次品留库、WAIT_CORRECTION等待更正、REJECT拒收、CLOSE结束处理',
 reason VARCHAR(1000) NOT NULL COMMENT '差异原因或原仓库事实说明',
 resolution_reason VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '人工处理依据，不替代实际仓库回传',
 actor VARCHAR(64) NOT NULL DEFAULT '' COMMENT '处理人，自动更正明确标记系统',
 resolution_receipt_id BIGINT NULL COMMENT '本次补建到货单ID，防止重复补建',
 control_version BIGINT NOT NULL DEFAULT 1 COMMENT '处理版本，并发操作仅允许一个生效',
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '差异记录建立时间',
 update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最近处理时间',
 UNIQUE KEY difference_fact(company_code,task_id,receipt_hash,difference_kind) COMMENT '重复回传不重复生成同类待办',
 KEY current_issue(company_code,state,create_time,id) COMMENT '当前待处理差异查询',
 KEY ticket_issue(company_code,ticket_id,state,id) COMMENT '按原采购入库单追溯差异',
 KEY message_issue(company_code,task_id,message_id) COMMENT '更正回传确认原消息差异'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='采购入库短收次品超收错货差异及处理，不直接增加库存';
