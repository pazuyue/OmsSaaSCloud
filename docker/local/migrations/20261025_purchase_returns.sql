CREATE TABLE IF NOT EXISTS purchase_return (
 id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '采购退货业务ID',
 company_code VARCHAR(64) NOT NULL COMMENT '所属公司',
 return_sn VARCHAR(64) NOT NULL COMMENT '采购退货单号，CGT前缀',
 request_key VARCHAR(64) NOT NULL COMMENT '创建请求幂等键',
 request_hash CHAR(64) NOT NULL COMMENT '创建内容摘要，重试内容须一致',
 purchase_id BIGINT NOT NULL COMMENT '原采购单ID，审核时作为来源数量互斥锁',
 po_sn VARCHAR(64) NOT NULL COMMENT '原采购单号快照',
 supplier_sn VARCHAR(64) NOT NULL COMMENT '原供应商编码',
 supplier_name VARCHAR(255) NOT NULL COMMENT '供应商名称快照',
 store_code VARCHAR(64) NOT NULL COMMENT '原入库虚仓，不得修改为其他库存来源',
 owner_code VARCHAR(64) NOT NULL COMMENT '原库存货主',
 real_store_code VARCHAR(255) NOT NULL COMMENT '原实体仓库编码',
 outbound_mode TINYINT NOT NULL COMMENT '出库方式，1真实仓库回传，2自动虚拟出库',
 state VARCHAR(24) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT草稿、APPROVING库存锁定中、APPROVED执行中、CANCELING取消核对中、CANCELED已取消或截停、COMPLETED全部出库、ATTENTION待处理',
 quantity BIGINT NOT NULL COMMENT '申请退供数量，实际单位见商品明细',
 accepted_quantity BIGINT NOT NULL DEFAULT 0 COMMENT '仓库已确认实际出库数量',
 posted_quantity BIGINT NOT NULL DEFAULT 0 COMMENT '已成功扣减库存数量',
 receipt_final TINYINT NOT NULL DEFAULT 0 COMMENT '仓库是否已最终结束本单出库，短出仍保留未执行占用直到截停',
 dispatch_state VARCHAR(24) NOT NULL DEFAULT 'UNSENT' COMMENT '仓库下发状态，与库存扣账结果独立',
 external_order VARCHAR(100) NOT NULL DEFAULT '' COMMENT '仓库外部单号',
 payload_json JSON NULL COMMENT '审核后固定的仓库下发快照，不含密钥',
 receiver_json JSON NOT NULL COMMENT '供应商收件联系人电话地址快照',
 carrier_code VARCHAR(64) NOT NULL COMMENT '仓库支持的退供物流编码',
 reason VARCHAR(1000) NOT NULL COMMENT '退供原因与协商依据',
 cancel_reason VARCHAR(200) NOT NULL DEFAULT '' COMMENT '撤回或停止剩余退供依据',
 stock_reserved TINYINT NOT NULL DEFAULT 0 COMMENT '库存服务已确认按本来源锁定',
 funds_state VARCHAR(24) NOT NULL DEFAULT 'UNRECORDED' COMMENT 'UNRECORDED未登记、REFUND已登记退款、CREDIT已登记抵扣；不是银行接口确认',
 funds_amount DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '人工凭证登记金额，不超过本单实际出库原采购货值',
 funds_evidence VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '供应商退款或抵扣凭证依据',
 control_version BIGINT NOT NULL DEFAULT 1 COMMENT '审核取消资金登记版本，防止覆盖并发处理',
 last_error VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '最近执行失败原因',
 created_by VARCHAR(64) NOT NULL COMMENT '创建人',
 approved_by VARCHAR(64) NOT NULL DEFAULT '' COMMENT '审核人',
 attempts INT NOT NULL DEFAULT 0 COMMENT '后台处理次数，用于失败退避',
 next_attempt_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '下一次自动补偿时间，等待仓库回传的单据不轮询执行',
 lease_token VARCHAR(64) NULL COMMENT '后台执行租约身份',
 lease_until DATETIME NULL COMMENT '后台执行租约到期时间',
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
 update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最近变更时间',
 UNIQUE KEY company_sn(company_code,return_sn) COMMENT '公司内退供单号唯一',
 UNIQUE KEY company_request(company_code,request_key) COMMENT '重复创建不重复生成退供单',
 KEY company_page(company_code,id) COMMENT '公司列表分页',
 KEY purchase_claim(company_code,purchase_id,state,id) COMMENT '原采购可退额度与退供汇总',
 KEY due_work(company_code,next_attempt_at,state,id) COMMENT '只扫描到期且需要执行的任务',
 KEY pending_work(company_code,state,lease_until,id) COMMENT '持久化自动任务补偿扫描'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='采购退货，原实收入库事实保留，仓库实际出库后扣账';
CREATE TABLE IF NOT EXISTS purchase_return_line (
 id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '退供明细ID，也是仓库行身份',
 company_code VARCHAR(64) NOT NULL COMMENT '所属公司',
 return_id BIGINT NOT NULL COMMENT '退供单ID',
 source_key VARCHAR(64) NOT NULL COMMENT '原入库来源，R实收明细ID或V虚拟入库商品行ID',
 ticket_sn VARCHAR(100) NOT NULL COMMENT '原采购入库执行单号',
 sku_sn VARCHAR(128) NOT NULL COMMENT '实际库存SKU，福袋须按实际组件',
 goods_name VARCHAR(255) NOT NULL COMMENT '原商品名称',
 stock_unit VARCHAR(16) NOT NULL COMMENT '采购时库存单位快照',
 batch_code VARCHAR(100) NOT NULL COMMENT '原实际库存批次',
 inventory_type VARCHAR(2) NOT NULL COMMENT 'ZP正品、CP次品；仓库协议次品使用CC',
 quantity BIGINT NOT NULL COMMENT '本次申请退供数量',
 source_quantity BIGINT NOT NULL COMMENT '原来源对应正次品成功入账数量快照',
 purchase_price DECIMAL(18,2) NOT NULL COMMENT '原采购单价，不使用当前商品售价',
 accepted_quantity BIGINT NOT NULL DEFAULT 0 COMMENT '实际出库累计数量',
 posted_quantity BIGINT NOT NULL DEFAULT 0 COMMENT '库存扣账累计数量',
 UNIQUE KEY source_grade(company_code,return_id,source_key,inventory_type) COMMENT '同单原来源质量明细不可重复',
 KEY source_claim(company_code,source_key,inventory_type,return_id) COMMENT '计算同一入库来源累计退供占用',
 KEY parent_lines(company_code,return_id,id) COMMENT '按退供单批量读取商品'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='采购退货来源与原批次成本快照';
CREATE TABLE IF NOT EXISTS purchase_return_event (
 id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '退供出库回传ID',
 company_code VARCHAR(64) NOT NULL COMMENT '所属公司',
 return_id BIGINT NOT NULL COMMENT '原退供单ID',
 message_id VARCHAR(128) NOT NULL COMMENT '仓库原消息号，虚拟执行为固定消息号',
 payload_hash CHAR(64) NOT NULL COMMENT '原回传内容摘要，相同消息内容变更禁止扣账',
 payload_json JSON NOT NULL COMMENT '已验签且匹配原仓库货主与行批次的出库增量',
 source_log_id BIGINT NOT NULL DEFAULT 0 COMMENT '原仓库交互日志ID，按需查脱敏报文',
 quantity BIGINT NOT NULL COMMENT '本次确认出库增量',
 state VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING待扣账、POSTED已扣账、FAILED扣账失败',
 last_error VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '本次库存扣账失败原因',
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '接收时间',
 UNIQUE KEY receipt_message(company_code,return_id,message_id) COMMENT '重复回传不重复扣账',
 KEY pending_post(company_code,return_id,state,id) COMMENT '只重试尚未成功事件'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='采购退货已确认出库原回传和独立扣账结果';
CREATE TABLE IF NOT EXISTS purchase_return_audit (
 id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '处理记录ID',company_code VARCHAR(64) NOT NULL COMMENT '所属公司',
 return_id BIGINT NOT NULL COMMENT '采购退货ID',action VARCHAR(32) NOT NULL COMMENT '动作',
 actor VARCHAR(64) NOT NULL COMMENT '操作人或自动流程',reason VARCHAR(1000) NOT NULL COMMENT '操作依据和结果',
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '记录时间',
 KEY parent_events(company_code,return_id,id) COMMENT '原单处理记录'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='采购退货审核取消资金登记与执行审计';
