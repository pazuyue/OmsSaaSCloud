-- 只保存退货查询投影，不作为审核、仓库下发或库存记账凭据。
CREATE TABLE IF NOT EXISTS oms_return_query_dirty (
 company_code VARCHAR(50) NOT NULL COMMENT '所属公司，查询投影严格按公司隔离',
 owner_kind VARCHAR(16) NOT NULL COMMENT 'REFUND业务退款或EXCHANGE换货',
 owner_id BIGINT NOT NULL COMMENT '业务退款ID或换货ID',
 work_version BIGINT NOT NULL DEFAULT 1 COMMENT '来源变化版本，投影完成后仅确认相同版本',
 lease_token VARCHAR(32) NULL COMMENT '短批投影租约，避免并发查询重复重建',
 lease_until DATETIME NULL COMMENT '投影租约到期时间，失败后可重新查询',
 PRIMARY KEY(company_code,owner_kind,owner_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='退货查询待更新来源，和业务变更同事务登记';

CREATE TABLE IF NOT EXISTS oms_return_query_row (
 id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '退货查询投影行ID，不用于业务操作',
 company_code VARCHAR(50) NOT NULL COMMENT '所属公司',
 view_kind VARCHAR(16) NOT NULL COMMENT 'TASK退货任务、PARCEL退回包裹、DOCUMENT实际入库单',
 group_key VARCHAR(160) NOT NULL COMMENT '当前视图聚合键，包裹和实际仓单只聚合一次',
 source_key VARCHAR(100) NOT NULL COMMENT '实际业务来源键，退款计划或换货来源',
 part_key VARCHAR(100) NOT NULL COMMENT '仓库来源代次键，撤回和重新安排分别保留',
 owner_kind VARCHAR(16) NOT NULL COMMENT '退款或换货归属',
 owner_id BIGINT NOT NULL COMMENT '业务退款或换货ID',
 owner_sn VARCHAR(64) NOT NULL COMMENT '业务退款单号或换货单号',
 source_id BIGINT NOT NULL DEFAULT 0 COMMENT '退款计划ID或换货ID，未建计划时为0',
 channel_id BIGINT NOT NULL COMMENT '所属店铺',
 order_id BIGINT NOT NULL COMMENT '原业务订单ID',
 order_sn VARCHAR(64) NOT NULL COMMENT '原业务订单号',
 platform_tid VARCHAR(100) NOT NULL COMMENT '原平台主订单号',
 platform_oid VARCHAR(100) NOT NULL COMMENT '原平台子订单号，资金身份与实物来源分别保留',
 sku_sn VARCHAR(128) NOT NULL DEFAULT '' COMMENT '实际退回SKU，换货后退回沿实际换出商品',
 goods_name VARCHAR(500) NOT NULL DEFAULT '' COMMENT '实际退回商品名称',
 unit VARCHAR(16) NOT NULL DEFAULT '件' COMMENT '实际库存单位，件与套分别汇总',
 is_gift TINYINT NOT NULL DEFAULT 0 COMMENT '是否为关联赠品退回',
 refund_only TINYINT NOT NULL DEFAULT 0 COMMENT '平台仅退款但确实存在退回安排',
 return_mode VARCHAR(24) NOT NULL DEFAULT 'RETURN' COMMENT 'RETURN寄回、INTERCEPT拦截、REFUSAL拒收',
 store_code VARCHAR(64) NOT NULL DEFAULT '' COMMENT '接收虚拟仓',
 real_store_code VARCHAR(255) NOT NULL DEFAULT '' COMMENT '实际接收仓',
 owner_code VARCHAR(64) NOT NULL DEFAULT '' COMMENT '库存货主',
 original_shipment_sn VARCHAR(64) NOT NULL DEFAULT '' COMMENT '原实际发货单号，保留换货来源链',
 outbound_waybills VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '原发货运单，仅追溯，不冒充退回运单',
 carrier VARCHAR(100) NOT NULL DEFAULT '' COMMENT '实际退回承运商',
 waybill VARCHAR(128) NOT NULL DEFAULT '' COMMENT '实际退回运单，未提供时为空',
 parcel_key VARCHAR(160) NOT NULL DEFAULT '' COMMENT '已关联包裹键；同运单不自动认定合包',
 parcel_sn VARCHAR(64) NOT NULL DEFAULT '' COMMENT '业务退回包裹号，独立退回可无编号',
 return_sn VARCHAR(64) NOT NULL DEFAULT '' COMMENT '实际下发仓库的退货入库单号，私有台账不作仓单',
 ticket_id BIGINT NULL COMMENT '实际仓库入库单台账ID',
 dispatch_after DATETIME NULL COMMENT '最后新增来源后的归集到期时间',
 quantity BIGINT NOT NULL DEFAULT 0 COMMENT '当前行明确应退数量，不从退款金额推算',
 quantity_known TINYINT NOT NULL DEFAULT 1 COMMENT '数量是否明确，待确认范围不显示为0件',
 accepted_quantity BIGINT NOT NULL DEFAULT 0 COMMENT '已明确归属的累计实收数量',
 posted_quantity BIGINT NOT NULL DEFAULT 0 COMMENT '已实际入库数量',
 waived_quantity BIGINT NOT NULL DEFAULT 0 COMMENT '经业务确认无需再退的数量',
 pending_count BIGINT NOT NULL DEFAULT 0 COMMENT '待核对实收消息数，公共消息不按成员重复累计',
 needs_check TINYINT NOT NULL DEFAULT 0 COMMENT '当前有归属、下发或来源异常需核对',
 active TINYINT NOT NULL DEFAULT 1 COMMENT '当前安排是否仍有效；已终止实收和入库继续保留',
 dispatched TINYINT NOT NULL DEFAULT 0 COMMENT '实际仓单是否已明确受理',
 warehouse_state VARCHAR(24) NOT NULL DEFAULT 'UNSENT' COMMENT '当前实际仓单受理或截停状态，与最近一次接口成败独立',
 interaction_result VARCHAR(16) NOT NULL DEFAULT '' COMMENT '最近一次仓库交互结果，查询失败不覆盖已受理状态',
 receipt_difference TINYINT NOT NULL DEFAULT 0 COMMENT '仓库已最终回传但本来源尚未收齐，含待核对归属的差异',
 expected_members INT NOT NULL DEFAULT 1 COMMENT '已关联包裹的实际来源项数，用于识别投影同步中',
 message VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '当前阻塞原因或来源处理说明',
 snapshot JSON NOT NULL COMMENT '仅查询用来源、仓单及成本快照，不含操作凭证或个人地址',
 create_time DATETIME NOT NULL COMMENT '当前视图来源或实际仓单建立时间',
 sync_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '最近核对投影时间，不冒充业务发生时间',
 UNIQUE KEY source_part(company_code,view_kind,source_key,part_key),
 KEY group_scope(company_code,view_kind,group_key),
 KEY owner_scope(company_code,owner_kind,owner_id),
 KEY page_scope(company_code,view_kind,create_time,id),
 KEY channel_page(company_code,view_kind,channel_id,create_time),
 KEY store_page(company_code,view_kind,store_code,create_time),
 KEY warehouse_page(company_code,view_kind,warehouse_state,create_time),
 KEY interaction_page(company_code,view_kind,interaction_result,create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='统一退货任务、包裹和实际入库单查询投影；各视图数量分别计算';

CREATE TABLE IF NOT EXISTS oms_return_query_number (
 company_code VARCHAR(50) NOT NULL COMMENT '所属公司',
 view_kind VARCHAR(16) NOT NULL COMMENT '所属查询视图',
 group_key VARCHAR(160) NOT NULL COMMENT '命中来源所关联的完整任务、包裹或仓单',
 owner_kind VARCHAR(16) NOT NULL COMMENT '业务来源类型，用于增量替换索引',
 owner_id BIGINT NOT NULL COMMENT '业务来源ID，用于增量替换索引',
 number_type VARCHAR(24) NOT NULL COMMENT '单号类型，包括原发货和实际退回运单',
 number_value VARCHAR(128) NOT NULL COMMENT '完整单号，支持多个单号精确匹配',
 PRIMARY KEY(company_code,view_kind,group_key,number_type,number_value,owner_kind,owner_id),
 KEY number_scope(company_code,number_type,number_value,view_kind),
 KEY number_any(company_code,number_value,view_kind),
 KEY owner_scope(company_code,owner_kind,owner_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='退货多种单号倒排索引；任一来源命中后仍展示完整合包数量';
