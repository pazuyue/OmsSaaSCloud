CREATE TABLE IF NOT EXISTS oms_order_shipment (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 company_code VARCHAR(50) COLLATE utf8mb4_bin NOT NULL,
 shipment_sn VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 order_id BIGINT NOT NULL,
 order_sn VARCHAR(64) NOT NULL,
 channel_id BIGINT NOT NULL,
 platform_tid VARCHAR(64) NOT NULL,
 generation_no BIGINT NOT NULL,
 owner_code VARCHAR(64) NOT NULL,
 real_store_code VARCHAR(255) NOT NULL,
 real_store_name VARCHAR(255) NOT NULL,
 store_code VARCHAR(255) NOT NULL DEFAULT '',
 quantity BIGINT NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'WAIT_CARRIER',
 receiver_name VARCHAR(200) NOT NULL DEFAULT '',
 receiver_phone VARCHAR(200) NOT NULL DEFAULT '',
 receiver_address VARCHAR(1000) NOT NULL DEFAULT '',
 oaid VARCHAR(200) NOT NULL DEFAULT '',
 created_by VARCHAR(100) NOT NULL,
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 cancelled_at DATETIME NULL,
 UNIQUE KEY shipment_number(company_code,shipment_sn),
 UNIQUE KEY shipment_wave(company_code,order_id,generation_no,owner_code,real_store_code,store_code),
 KEY shipment_order(company_code,order_id,id),
 KEY shipment_page(company_code,status,id),
 KEY shipment_platform(company_code,channel_id,platform_tid)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='按分仓增量和虚拟仓生成的履约发货单';

CREATE TABLE IF NOT EXISTS oms_order_shipment_line (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 company_code VARCHAR(50) COLLATE utf8mb4_bin NOT NULL,
 shipment_id BIGINT NOT NULL,
 allocation_id BIGINT NOT NULL,
 order_line_id BIGINT NOT NULL,
 platform_oid VARCHAR(64) NOT NULL,
 sku_sn VARCHAR(128) NOT NULL,
 goods_name VARCHAR(500) NOT NULL,
 store_code VARCHAR(64) NOT NULL,
 batch_id BIGINT NOT NULL,
 source_type VARCHAR(24) NOT NULL,
 stock_source_id BIGINT NOT NULL,
 quantity BIGINT NOT NULL,
 shipped_quantity BIGINT NOT NULL DEFAULT 0,
 UNIQUE KEY receipt_once(company_code,allocation_id),
 KEY shipment_lines(company_code,shipment_id,id),
 KEY shipment_sku(company_code,sku_sn,shipment_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='每条占用回执仅归属一个发货单，保留虚仓与批次追溯';
