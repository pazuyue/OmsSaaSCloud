-- 新增公共物理退回层；不回填历史退款、HH或仓库单据。
CREATE TABLE IF NOT EXISTS wms_shared_return_parcel (
 id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '共同物理包裹ID，区别于业务退款和HH',
 company_code VARCHAR(50) NOT NULL COMMENT '所属公司，不跨公司合包',
 parcel_sn VARCHAR(64) NOT NULL COMMENT 'OMS包裹号，不当作仓库THK',
 channel_id BIGINT NOT NULL COMMENT '所属店铺，不跨店合包',
 platform_tid VARCHAR(100) NOT NULL COMMENT '原平台订单，不跨单自动合包',
 carrier_code VARCHAR(64) NOT NULL COMMENT '已确认退回承运商',
 waybill VARCHAR(128) NOT NULL COMMENT '买家实际退回运单',
 store_code VARCHAR(64) NOT NULL COMMENT '共同接收虚拟仓',
 connection_id BIGINT NOT NULL COMMENT '已核对的仓库连接',
 external_owner VARCHAR(100) NOT NULL COMMENT '接口货主',
 external_warehouse VARCHAR(100) NOT NULL COMMENT '接口仓库',
 owner_code VARCHAR(64) NOT NULL COMMENT '库存货主',
 real_store_code VARCHAR(64) NOT NULL COMMENT '实际仓',
 dispatch_after DATETIME NOT NULL COMMENT '最后实际新增成员后的归集到期时间；重复通知不延期',
 control_version BIGINT NOT NULL DEFAULT 1 COMMENT '归集、实收及共同操作的乐观锁版本',
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
 UNIQUE KEY physical_scope(company_code,channel_id,platform_tid,carrier_code,waybill) COMMENT '同店同单同运单仅一包；仓库冲突阻断',
 UNIQUE KEY sn_scope(company_code,parcel_sn) COMMENT '公司内包裹号唯一',
 KEY due(company_code,dispatch_after,id) COMMENT '按公司定位到期包裹'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='共同退回包裹：只合物流，退款与换货业务独立';

CREATE TABLE IF NOT EXISTS wms_shared_return_member (
 id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '共同THK明细身份，作为仓库回传行号',
 company_code VARCHAR(50) NOT NULL COMMENT '所属公司',
 parcel_id BIGINT NOT NULL COMMENT '共同包裹',
 owner_kind VARCHAR(16) NOT NULL COMMENT 'REFUND退款或EXCHANGE换货，与ID共同限定业务归属',
 owner_id BIGINT NOT NULL COMMENT '原业务退款ID或原HH ID',
 owner_sn VARCHAR(64) NOT NULL COMMENT '原业务退款号或HH号',
 source_id BIGINT NOT NULL COMMENT '退款退回计划ID或HH ID，不按SKU合并来源',
 task_id BIGINT NOT NULL COMMENT '对应类型原仓库来源任务ID，沿原发货成本记账',
 order_sn VARCHAR(64) NOT NULL COMMENT '原SO编号',
 platform_oid VARCHAR(100) NOT NULL COMMENT '原平台子订单',
 sku_sn VARCHAR(128) NOT NULL COMMENT '实际应退SKU',
 quantity BIGINT NOT NULL COMMENT '该来源应退数量，合包或短收不静默缩减',
 source_hash CHAR(64) NOT NULL COMMENT '不可变仓库来源及业务范围摘要',
 mixed_allowed TINYINT NOT NULL DEFAULT 0 COMMENT '商家是否授权与另一售后类型合包',
 dispatch_allowed TINYINT NOT NULL DEFAULT 0 COMMENT '是否授权自动下发；所有成员均允许才发送',
 allocate_allowed TINYINT NOT NULL DEFAULT 0 COMMENT '是否授权无歧义实收自动分配',
 policy_revision BIGINT NOT NULL COMMENT '授权此来源动作的业务规则版本',
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '实际加入时间，决定归集窗口',
 UNIQUE KEY source_scope(company_code,owner_kind,source_id) COMMENT '同一实际来源只归入一个共同包裹',
 KEY parcel_scope(company_code,parcel_id,id) COMMENT '按包有界读成员',
 KEY owner_scope(company_code,owner_kind,owner_id,id) COMMENT '按退款或HH有界读包裹'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='共同退回来源：保留退款、HH及实际发货来源身份';

CREATE TABLE IF NOT EXISTS wms_shared_return_document (
 id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '共同仓库命令ID',
 company_code VARCHAR(50) NOT NULL COMMENT '所属公司',
 parcel_id BIGINT NOT NULL COMMENT '所属物理包裹',
 return_sn VARCHAR(64) NOT NULL COMMENT '实际下发的共同THK，私有来源单不下发',
 ticket_id BIGINT NULL COMMENT '共同退货入库单台账',
 quantity BIGINT NOT NULL COMMENT '冻结时各来源计划合计，仅为物理总量',
 accepted_quantity BIGINT NOT NULL DEFAULT 0 COMMENT '各私有来源已分配实收汇总，仅投影不作为库存记账凭据',
 posted_quantity BIGINT NOT NULL DEFAULT 0 COMMENT '各私有来源已入库汇总，原来源入账后更新',
 pending_receipt_count BIGINT NOT NULL DEFAULT 0 COMMENT '待逐行确认归属的仓库回传数',
 pending_quantity BIGINT NOT NULL DEFAULT 0 COMMENT '待确认归属的回传数量，不计入已实收或可用库存',
 payload JSON NOT NULL COMMENT '冻结的成员、来源和数量快照',
 dispatch_state VARCHAR(24) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING待发、SENDING提交中、UNKNOWN未知、ACCEPTED接单、FAILED失败、CANCELED截停',
 external_order VARCHAR(128) NOT NULL DEFAULT '' COMMENT '仓库明确返回的受理号',
 warehouse_status VARCHAR(64) NOT NULL DEFAULT '' COMMENT '仓库状态，不代替实收入账',
 cancel_state VARCHAR(24) NOT NULL DEFAULT 'NONE' COMMENT 'NONE未取消、PENDING待截停、UNKNOWN待核对、CONFIRMED已确认、REJECTED拒绝',
 attempts INT NOT NULL DEFAULT 0 COMMENT '原CREATE次数；结果未知仅查询',
 control_version BIGINT NOT NULL DEFAULT 1 COMMENT '命令及截单版本',
 last_error VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '仓库交互或归属问题',
 lease_token VARCHAR(32) NULL COMMENT '共同命令租约',
 lease_until DATETIME NULL COMMENT '租约到期时间',
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '冻结时间，不早于归集到期',
 UNIQUE KEY parcel_scope(company_code,parcel_id) COMMENT '每个物理包裹一份共同THK',
 UNIQUE KEY sn_scope(company_code,return_sn) COMMENT '按回传仓库单号定位原共同单'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='共同退回仓库命令及受理结果，库存仍按来源入账';

CREATE TABLE IF NOT EXISTS wms_shared_return_receipt (
 id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '共同仓库实收事件ID',
 company_code VARCHAR(50) NOT NULL COMMENT '所属公司',
 parcel_id BIGINT NOT NULL COMMENT '所属物理包裹',
 document_id BIGINT NOT NULL COMMENT '验签并核对身份后的原共同THK',
 message_id VARCHAR(128) NOT NULL COMMENT '仓库事件号，同消息内容不可改变',
 payload_hash CHAR(64) NOT NULL COMMENT '原回传摘要，防止同消息不同数量',
 payload JSON NOT NULL COMMENT '原回传行号、SKU、批次、良次品及最终确认标志',
 quantity BIGINT NOT NULL DEFAULT 0 COMMENT '本条原仓库消息实收总数，归属未确认前不入库',
 state VARCHAR(24) NOT NULL DEFAULT 'WAIT_ALLOCATION' COMMENT 'WAIT_ALLOCATION待归属、ALLOCATED已分配、REJECTED人工拒绝',
 allocation_json JSON NULL COMMENT '逐行分到各成员的数量，良次品分别守恒',
 allocation_method VARCHAR(16) NOT NULL DEFAULT '' COMMENT 'AUTO明确行号或唯一SKU、AUTO_BLOCKED明确冲突不重复运算、MANUAL人工确认',
 source_log_id BIGINT NOT NULL COMMENT '原验签交互日志',
 actor VARCHAR(64) NOT NULL DEFAULT '' COMMENT '分配人或自动规则',
 reason VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '分配结论或阻塞原因',
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '实际接收时间',
 UNIQUE KEY event_scope(company_code,parcel_id,message_id) COMMENT '并发重复回传只留一份事实',
 KEY parcel_state(company_code,parcel_id,state,id) COMMENT '有界核对本包待分配实收'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='共同回传与逐来源分配：未明确分配不增加库存';
