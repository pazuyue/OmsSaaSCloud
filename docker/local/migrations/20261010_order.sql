-- Document service: Tmall pull and conversion only. Push database is read-only.
CREATE TABLE IF NOT EXISTS oms_order_pull_config (
 id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '配置ID',
 company_code VARCHAR(50) COLLATE utf8mb4_bin NOT NULL COMMENT '公司编码',
 channel_id BIGINT NOT NULL COMMENT '店铺ID',
 channel_name VARCHAR(200) NOT NULL COMMENT '店铺名称快照',
 source_key VARCHAR(64) NOT NULL COMMENT '服务端推送库连接标识，不存储连接密码',
 seller_nick VARCHAR(200) COLLATE utf8mb4_bin NOT NULL COMMENT '推送库卖家账号',
 owner_code VARCHAR(64) NOT NULL COMMENT '库存货主',
 store_codes TEXT NOT NULL COMMENT '允许使用的虚仓编码JSON',
 enabled TINYINT NOT NULL DEFAULT 0 COMMENT '自动拉单开关',
 auto_convert TINYINT NOT NULL DEFAULT 1 COMMENT '自动转单开关',
 allow_public_stock TINYINT NOT NULL DEFAULT 0 COMMENT '允许超出本渠道额度补占公共库存',
 interval_seconds INT NOT NULL DEFAULT 30 COMMENT '自动拉单间隔秒',
 initial_time DATETIME NOT NULL COMMENT '首次拉单起点，推送更新时间',
 cursor_time DATETIME NOT NULL COMMENT '已完成自动拉单的推送更新时间',
 next_run_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '下次自动调度时间',
 lease_token VARCHAR(32) NULL COMMENT '店铺执行租约标识',
 lease_until DATETIME NULL COMMENT '租约截止时间',
 last_error VARCHAR(500) NOT NULL DEFAULT '' COMMENT '最后一次任务错误',
 revision INT NOT NULL DEFAULT 1 COMMENT '配置版本',
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uk_company_channel(company_code,channel_id),
 UNIQUE KEY uk_source_seller(source_key,seller_nick),
 KEY idx_pull_due(enabled,next_run_at,company_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='天猫订单拉取与转单配置，按公司店铺隔离';

CREATE TABLE IF NOT EXISTS oms_order_pull_task (
 id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '任务ID',
 company_code VARCHAR(50) COLLATE utf8mb4_bin NOT NULL,
 channel_id BIGINT NOT NULL,
 task_type VARCHAR(12) NOT NULL COMMENT 'AUTO自动，MANUAL补拉',
 start_time DATETIME NOT NULL COMMENT '推送更新时间起点，包含',
 end_time DATETIME NOT NULL COMMENT '推送更新时间截止，不包含',
 page_time DATETIME NOT NULL COMMENT '本任务分页游标时间',
 page_tid BIGINT NOT NULL DEFAULT 0 COMMENT '本任务分页游标平台订单号',
 status VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING/RUNNING/SUCCESS/FAILED',
 pulled_count INT NOT NULL DEFAULT 0,
 inserted_count INT NOT NULL DEFAULT 0,
 duplicate_count INT NOT NULL DEFAULT 0,
 attempts INT NOT NULL DEFAULT 0,
 next_retry_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 error_message VARCHAR(500) NOT NULL DEFAULT '',
 operator_name VARCHAR(100) NOT NULL,
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY idx_shop_task(company_code,channel_id,status,task_type,id),
 KEY idx_task_page(company_code,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='拉单与补拉任务，补拉不修改自动游标';

CREATE TABLE IF NOT EXISTS oms_platform_order (
 id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '原始订单ID',
 company_code VARCHAR(50) COLLATE utf8mb4_bin NOT NULL,
 channel_id BIGINT NOT NULL,
 platform VARCHAR(16) NOT NULL DEFAULT 'TMALL',
 platform_tid VARCHAR(64) COLLATE utf8mb4_bin NOT NULL COMMENT '平台订单号，字符串避免精度损失',
 platform_status VARCHAR(64) NOT NULL DEFAULT '',
 trade_type VARCHAR(64) NOT NULL DEFAULT '',
 seller_nick VARCHAR(200) NOT NULL DEFAULT '',
 platform_created DATETIME NULL,
 platform_modified DATETIME NULL,
 source_modified DATETIME NOT NULL,
 payload_hash CHAR(64) NOT NULL,
 raw_payload MEDIUMTEXT NOT NULL COMMENT '平台原始报文，仅授权详情可读',
 processing_payload MEDIUMTEXT NULL COMMENT '首次登记需求前固定的转单报文快照',
 processing_hash CHAR(64) NULL,
 conversion_status VARCHAR(24) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING/PROCESSING/WAITING/EXCEPTION/SUCCESS',
 conversion_error VARCHAR(500) NOT NULL DEFAULT '',
 change_pending TINYINT NOT NULL DEFAULT 0 COMMENT '需求登记后原始业务数据变化，二期处理',
 demand_registered TINYINT NOT NULL DEFAULT 0,
 force_convert TINYINT NOT NULL DEFAULT 0 COMMENT '人工重试请求转单',
 next_retry_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 business_order_id BIGINT NULL,
 payment DECIMAL(18,2) NULL,
 receiver_name VARCHAR(200) NOT NULL DEFAULT '',
 receiver_phone VARCHAR(200) NOT NULL DEFAULT '',
 receiver_address VARCHAR(1000) NOT NULL DEFAULT '',
 oaid VARCHAR(200) NOT NULL DEFAULT '',
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uk_platform_order(company_code,channel_id,platform_tid),
 KEY idx_platform_page(company_code,id),
 KEY idx_platform_state(company_code,channel_id,conversion_status,next_retry_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='天猫原始订单及转单处理状态';

CREATE TABLE IF NOT EXISTS oms_platform_order_line (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 company_code VARCHAR(50) COLLATE utf8mb4_bin NOT NULL,
 platform_order_id BIGINT NOT NULL,
 platform_oid VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 platform_item_id VARCHAR(64) NOT NULL DEFAULT '',
 platform_sku_id VARCHAR(64) NOT NULL DEFAULT '',
 outer_sku_id VARCHAR(128) NOT NULL DEFAULT '',
 outer_iid VARCHAR(128) NOT NULL DEFAULT '',
 title VARCHAR(500) NOT NULL DEFAULT '',
 quantity INT NOT NULL,
 payment DECIMAL(18,2) NULL,
 sku_sn VARCHAR(128) NULL COMMENT '匹配到的内部SKU',
 match_error VARCHAR(500) NOT NULL DEFAULT '',
 UNIQUE KEY uk_platform_line(platform_order_id,platform_oid),
 KEY idx_line_company(company_code,platform_order_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='平台订单明细与商品匹配结果';

CREATE TABLE IF NOT EXISTS oms_order (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 company_code VARCHAR(50) COLLATE utf8mb4_bin NOT NULL,
 order_sn VARCHAR(64) COLLATE utf8mb4_bin NOT NULL COMMENT 'SO加UUID，无下划线',
 channel_id BIGINT NOT NULL,
 platform_order_id BIGINT NOT NULL,
 platform_tid VARCHAR(64) NOT NULL,
 owner_code VARCHAR(64) NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'WAIT_ALLOCATION' COMMENT '一期待分仓',
 inventory_status VARCHAR(24) NOT NULL COMMENT 'WAIT_RESERVE/PART_RESERVED/RESERVED',
 payment DECIMAL(18,2) NOT NULL,
 receiver_name VARCHAR(200) NOT NULL DEFAULT '',
 receiver_phone VARCHAR(200) NOT NULL DEFAULT '',
 receiver_address VARCHAR(1000) NOT NULL DEFAULT '',
 oaid VARCHAR(200) NOT NULL DEFAULT '',
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uk_business_platform(company_code,channel_id,platform_tid),
 UNIQUE KEY uk_order_sn(company_code,order_sn),
 KEY idx_order_page(company_code,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='OMS业务订单，一期普通天猫订单';

CREATE TABLE IF NOT EXISTS oms_order_line (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 company_code VARCHAR(50) COLLATE utf8mb4_bin NOT NULL,
 order_id BIGINT NOT NULL,
 platform_oid VARCHAR(64) NOT NULL,
 sku_sn VARCHAR(128) NOT NULL,
 goods_name VARCHAR(500) NOT NULL,
 quantity INT NOT NULL,
 payment DECIMAL(18,2) NOT NULL,
 reserved_quantity INT NOT NULL DEFAULT 0,
 inventory_reason VARCHAR(500) NOT NULL DEFAULT '',
 UNIQUE KEY uk_order_line(order_id,platform_oid)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='OMS业务订单明细及逻辑预占结果';

CREATE TABLE IF NOT EXISTS oms_order_process_log (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 company_code VARCHAR(50) COLLATE utf8mb4_bin NOT NULL,
 platform_order_id BIGINT NOT NULL,
 action VARCHAR(32) NOT NULL,
 result VARCHAR(24) NOT NULL,
 message VARCHAR(500) NOT NULL,
 operator_name VARCHAR(100) NOT NULL,
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY idx_order_log(company_code,platform_order_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='订单需求登记、转单、重试日志，不记录凭据';
