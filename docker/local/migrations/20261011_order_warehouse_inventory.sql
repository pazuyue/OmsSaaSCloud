CREATE TABLE IF NOT EXISTS oms_order_warehouse_allocation (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 company_code VARCHAR(50) NOT NULL,
 channel_id BIGINT NOT NULL,
 platform_tid VARCHAR(64) NOT NULL,
 demand_id BIGINT NOT NULL,
 stock_source_id BIGINT NOT NULL,
 sku_sn VARCHAR(128) NOT NULL,
 source_type VARCHAR(24) NOT NULL,
 batch_id BIGINT NOT NULL,
 store_code VARCHAR(64) NOT NULL,
 owner_code VARCHAR(64) NOT NULL,
 real_store_code VARCHAR(255) NOT NULL,
 real_store_name VARCHAR(255) NOT NULL,
 quantity BIGINT NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'OCCUPIED',
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY order_scope(company_code,channel_id,platform_tid,status),
 KEY source_scope(company_code,stock_source_id,status),
 KEY demand_scope(company_code,demand_id,status),
 KEY batch_scope(company_code,batch_id,source_type,status),
 KEY public_scope(company_code,sku_sn,source_type,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
