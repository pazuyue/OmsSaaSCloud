CREATE TABLE IF NOT EXISTS wms_outbound_task (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 company_code VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 shipment_id BIGINT NOT NULL,
 shipment_sn VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 connection_id BIGINT NOT NULL,
 external_warehouse VARCHAR(100) NOT NULL,
 external_owner VARCHAR(100) NOT NULL,
 owner_code VARCHAR(64) NOT NULL,
 real_store_code VARCHAR(255) NOT NULL,
 payload_json MEDIUMTEXT NOT NULL,
 payload_hash VARCHAR(64) NOT NULL,
 dispatch_state VARCHAR(24) NOT NULL DEFAULT 'PENDING',
 external_order VARCHAR(100) NOT NULL DEFAULT '',
 warehouse_status VARCHAR(40) NOT NULL DEFAULT '',
 attempts INT NOT NULL DEFAULT 0,
 lease_token VARCHAR(64) NULL,
 lease_until DATETIME NULL,
 last_error VARCHAR(1000) NOT NULL DEFAULT '',
 query_message VARCHAR(1000) NOT NULL DEFAULT '',
 last_query_time DATETIME NULL,
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 modify_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY outbound_document(company_code,shipment_id),
 UNIQUE KEY outbound_number(company_code,shipment_sn)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='发货单真实WMS下发任务，复用采购入库连接及交互日志';
